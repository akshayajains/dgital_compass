/**
 * Lookup a variant by style + variant id.
 * Returns null for standalone themes (no variants).
 */
export const getVariant = (styleId: CompassStyleId, variantId: string): CompassStyleVariant | null => {
  const style = COMPASS_STYLES.find(s => s.id === styleId);
  if (!style?.variants) return null;
  return style.variants.find(v => v.id === variantId) ?? null;
};

/**
 * Get the default variant id for a grouped theme.
 */
export const getDefaultVariantId = (styleId: CompassStyleId): string | null => {
  const style = COMPASS_STYLES.find(s => s.id === styleId);
  if (!style?.variants?.length) return null;
  return style.variants[0].id;
};
