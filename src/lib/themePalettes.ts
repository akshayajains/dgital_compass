/**
 * Returns the unified theme palette based on selected style and variant.
 * Single source of truth across the whole application.
 */
export function getAppThemePalette(styleId?: string | null, variantId?: string | null): AppThemePalette {
  if (styleId === 'sandalwood') return PALETTES.sandalwood;
  if (styleId === 'royal_gold') return PALETTES.royal_gold;
  if (styleId === 'vedic_mandala') return PALETTES.vedic_mandala;
  if (styleId === 'satellite_earth') return PALETTES.satellite_earth;
  if (variantId && PALETTES[variantId]) return PALETTES[variantId];
  return PALETTES.ios_black;
}
